/*
 * Inlines index.html into a single self-contained file.
 *
 * No dependencies on purpose: this runs in CI where Node exists, while the
 * app itself must stay build-free so it can be opened straight from disk.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const outDir = join(repo, 'dist');
const outFile = join(outDir, 'scheduler-local.html');

const read = (rel) => readFileSync(join(repo, rel), 'utf8');

// A literal </script> inside inlined JS would close the wrapper tag early.
const guardScript = (js) => js.replace(/<\/script/gi, '<\\/script');

// Same hazard for </style> inside CSS, plus stray closing comments.
const guardStyle = (css) => css.replace(/<\/style/gi, '<\\/style');

const original = read('index.html');
let html = original;
const inlined = [];

html = html.replace(
  /<link\s+rel="stylesheet"\s+href="([^"]+)"([^>]*)>/gi,
  (match, href, rest) => {
    if (/^https?:/i.test(href)) return match;
    const mediaMatch = rest.match(/media="([^"]+)"/i);
    const media = mediaMatch ? ` media="${mediaMatch[1]}"` : '';
    inlined.push(href);
    return `<style${media}>\n${guardStyle(read(href))}\n</style>`;
  }
);

html = html.replace(
  /<script\s+src="([^"]+)"\s*><\/script>/gi,
  (match, src) => {
    if (/^https?:/i.test(src)) return match;
    inlined.push(src);
    return `<script>\n${guardScript(read(src))}\n</script>`;
  }
);

/*
 * Check the original markup, not the bundled output: the vendored libraries
 * contain their own src=" strings in ordinary code, which would look like
 * unresolved references once inlined.
 */
const references = original.match(/(?:href|src)="(?!data:|https?:|mailto:|#)[^"]+"/gi) || [];
const unresolved = references.filter(
  (ref) => !inlined.some((file) => ref === `href="${file}"` || ref === `src="${file}"`)
);
if (unresolved.length) {
  console.error('Refusing to write a bundle with unresolved local references:');
  unresolved.forEach((l) => console.error('  ' + l));
  process.exit(1);
}

// The one place the version is written down, so the bundle cannot claim a
// different one from the app inside it.
const version = (read('assets/js/util.js').match(/VERSION = '([^']+)'/) || [, 'unknown'])[1];

const banner = `<!-- Chatt State Life Science Tutor Schedule ${version} — single-file build.
     Generated by tools/bundle.mjs on ${new Date().toISOString().slice(0, 10)}.
     Open this file in any browser; it works offline and saves your work
     in that browser's local storage. -->\n`;

html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner);

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, html, 'utf8');

console.log(`Inlined ${inlined.length} files:`);
inlined.forEach((f) => console.log('  ' + f));
console.log(`\nWrote ${outFile} (${(html.length / 1024).toFixed(0)} KB)`);
